"""Read the live fluxion graph.

Read-only. The qdevice vertices are part of the static scheduling graph the
broker is configured with ([resource] scheduling, generated by
flux_quantum.schedjgf), so nothing here mutates fluxion. The old populate /
add_subgraph path is gone on purpose: growing a live graph while jobs hold
allocations corrupts planner spans permanently, and two writers racing one
graph corrupt it structurally. A static graph makes both unreachable.

The find RPC is owner-only in a system instance, so ordinary users read
through the CLI plugin's validator rather than directly.
"""

import json

from . import qresource

try:
    from flux.resource import resource_list
except ImportError:
    resource_list = None


def get_live_graph(handle, criteria="status=up"):
    """Return the live fluxion graph of nodes and edges from the find RPC."""
    try:
        resp = handle.rpc(
            "sched-fluxion-resource.find",
            {"criteria": criteria, "format": "jgf"},
        ).get()
    except Exception as exc:
        raise RuntimeError(
            "sched-fluxion-resource.find RPC failed (is fluxion loaded, and are "
            "you the instance owner?): {}".format(exc)
        )
    if "R" not in resp:
        raise RuntimeError("find response missing 'R': {!r}".format(resp))
    doc = resp["R"]
    if isinstance(doc, str):
        doc = json.loads(doc)
    if "graph" in doc:
        return doc["graph"]
    if "scheduling" in doc and "graph" in doc["scheduling"]:
        return doc["scheduling"]["graph"]
    raise ValueError("find response has no graph")


def orphaned_vendors(graph):
    """Vendors whose qdevice vertex is in the graph but unreachable from the
    root over containment edges.

    With a static scheduling graph this cannot happen (schedjgf.check refuses
    to emit such a file), so a non-empty answer on a live instance means the
    graph was mutated by something else and the instance needs a restart.
    Kept as the cheap corruption probe the preflight checks run.
    """
    # not find_root: it defines the root as the only vertex with no incoming
    # edge, so on exactly the corrupt graph this detects, an orphan looks
    # like a second root and it raises before the diagnosis is made
    roots = [n for n in graph["nodes"] if n["metadata"]["type"] == "cluster"]
    if len(roots) != 1:
        return set()  # not a shape this can judge
    root = roots[0]
    children = {}
    for edge in graph["edges"]:
        # fluxion's find writer emits bare {source, target} with no metadata,
        # while a scheduling JGF names the subsystem. Anything that does not
        # say it is another subsystem counts as containment.
        sub = edge.get("metadata", {}).get("subsystem", "containment")
        if sub == "containment":
            children.setdefault(edge["source"], []).append(edge["target"])
    seen = set()
    stack = [root["id"]]
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        stack.extend(children.get(cur, ()))
    out = set()
    for n in graph["nodes"]:
        t = n["metadata"]["type"]
        if t.startswith(qresource.QDEVICE_PREFIX) and n["id"] not in seen:
            out.add(t[len(qresource.QDEVICE_PREFIX) :])
    return out


def vendors_present(graph):
    """Vendor names already in the graph (from qdevice_<vendor> vertices)."""
    out = set()
    for n in graph["nodes"]:
        t = n["metadata"]["type"]
        if t.startswith(qresource.QDEVICE_PREFIX):
            out.add(t[len(qresource.QDEVICE_PREFIX) :])
    return out


def allocated_cores(handle, lister=None):
    """Cores the scheduler currently has allocated."""
    lister = lister or resource_list
    if lister is None:
        raise RuntimeError("the flux bindings are not importable")
    return int(lister(handle).get().allocated.ncores)
